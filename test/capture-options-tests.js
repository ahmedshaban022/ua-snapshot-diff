'use strict';
const assert = require('node:assert/strict');
const C = require('../shared/capturecore.js');
const prep = { viewportHeight: 800, scrollHeight: 3000, startY: 500 };
assert.deepEqual(C.plan(prep, { mode: 'viewport' }).offsets, [500]);
assert.equal(C.plan(prep, { mode: 'viewport' }).totalH, 800);
const two = C.plan(prep, { mode: 'screens', screenCount: 2 });
assert.deepEqual(two.offsets, [500, 1300]);
assert.equal(two.totalH, 1600);
assert.equal(two.startY, 500);
const top = C.plan(prep, { mode: 'screens', screenCount: 2, start: 'top' });
assert.deepEqual(top.offsets, [0, 800]);
const tail = C.plan({ ...prep, startY: 1800 }, { mode: 'screens', screenCount: 3 }, 2, 2000);
assert.deepEqual(tail.offsets, [1800, 2200]);
assert.deepEqual(tail.ys, [0, 800]);
assert.equal(tail.totalH, 2400);
assert.equal(tail.reachedBottom, true);
assert.equal(tail.truncated, false);
const full = C.plan(prep, { mode: 'full' });
assert.deepEqual(full.offsets, [0, 800, 1600, 2200]);
assert.equal(full.totalH, 3000);
assert.throws(() => C.options({ mode: 'screens', screenCount: 0 }), /between 1 and 20/);
assert.throws(() => C.options({ mode: 'screens', screenCount: 21 }), /between 1 and 20/);
assert.throws(() => C.options({ mode: 'screens', screenCount: 2.5 }), /between 1 and 20/);
assert.throws(() => C.options({ mode: 'anything' }), /Choose/);
const huge = C.plan({ viewportHeight: 1000, scrollHeight: 100000, startY: 0 }, { mode: 'full' }, 2, 4000);
assert.equal(huge.totalH, 16000);
assert.equal(huge.truncated, true);
assert.equal(C.filename({ label: 'test / screenshot: 1' }), 'test - screenshot- 1.png');
console.log('PASS visible, counted, full-page, bottom-edge, scaled, bounded, and invalid capture sizes');
